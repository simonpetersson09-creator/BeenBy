const base: Record<Lang, Dict> = { sv, en, de, da, fi, es, fr, nb, nl };

const dicts: Record<Lang, Dict> = Object.fromEntries(
  (Object.keys(base) as Lang[]).map((code) => [code, { ...base[code], ...appDicts[code] }]),
) as Record<Lang, Dict>;

/** Intl locale used for dates and numbers per app language. */
export const LOCALES: Record<Lang, string> = {
  sv: "sv-SE",
  en: "en-GB",
  de: "de-DE",
  da: "da-DK",
  nb: "nb-NO",
  fi: "fi-FI",
  nl: "nl-NL",
  es: "es-ES",
  fr: "fr-FR",
};

export function localeOf(lang: Lang = getLang()): string {
  return LOCALES[lang] ?? "en-GB";
}

export function translate(lang: Lang, key: string, vars?: Record<string, string>): string {
  const raw = dicts[lang]?.[key] ?? en[key] ?? sv[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v), raw);
}

export function useT() {
  const lang = useLang();
  return (key: string, vars?: Record<string, string>) => translate(lang, key, vars);
}

/**
 * "Mamma"/"Pappa" are stored as canonical Swedish values in the database.
 * Show them in the reader's language; custom names are returned untouched.
 */
export function personLabel(name: string | null | undefined, lang: Lang = getLang()): string {
  const value = (name ?? "").trim();
  const key = value.toLowerCase();
  if (key === "mamma") return translate(lang, "vem.mamma");
  if (key === "pappa") return translate(lang, "vem.pappa");
  return value;
}

export function usePersonLabel() {
  const lang = useLang();
  return (name: string | null | undefined) => personLabel(name, lang);
}
